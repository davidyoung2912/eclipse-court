/// <reference types="node" />
import { writeFileSync } from 'node:fs'
import { COURTS } from '../engine/rules/board'
import { buildTable, LUMS, roleStrength, ROLES } from './matchups'

const args = process.argv.slice(2)
const flag = (name: string, fallback: number) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 ? Number(args[i + 1]) : fallback
}
const samples = flag('samples', 150)
const skill = flag('skill', 0.8)
const write = args.includes('--write')
const OUT = new URL('../engine/data/matchupData.ts', `file://${process.cwd()}/src/sim/`)

const t0 = Date.now()
const table = buildTable(samples, skill, (court, att) => process.stderr.write(`${court} ${att}\n`))

const pct = (x: number) => `${Math.round(x * 100)}%`.padStart(4)
console.log(`\nMatchup report: ${samples} duels per cell, skill ${skill}, ${((Date.now() - t0) / 1000).toFixed(0)}s`)
console.log('\nRole strength (win rate over every matchup at dusk, either side of the attack):')
for (const role of ROLES) console.log(`  ${role.padEnd(12)} ${pct(roleStrength(table, role))}`)

console.log('\nAttacker win % at dusk, rows attack columns (Solari attacking Umbral):')
console.log(`  ${''.padEnd(12)} ${ROLES.map((r) => r.slice(0, 4).padStart(5)).join('')}`)
for (const att of ROLES)
  console.log(`  ${att.padEnd(12)} ${ROLES.map((def) => pct(table.solari[att][def][2].attacker).padStart(5)).join('')}`)

// Strong pieces should usually win, never always: flag cells that are hopeless or a coin-flip-free wall.
const lopsided: string[] = []
let decisive = 0
let cells = 0
for (const court of COURTS)
  for (const att of ROLES)
    for (const def of ROLES)
      LUMS.forEach((l, i) => {
        const m = table[court][att][def][i]
        cells++
        if (m.attacker + m.defender > 0.5) decisive++
        if (m.attacker >= 0.98 || m.defender >= 0.98) lopsided.push(`${court} ${att} vs ${def} @${l}: ${pct(m.attacker)}/${pct(m.defender)}`)
      })
console.log(`\n${decisive}/${cells} cells resolve a winner more than half the time.`)
console.log(`${lopsided.length} cells are a 98%+ certainty${lopsided.length ? ':' : '.'}`)
for (const l of lopsided.slice(0, 40)) console.log(`  ${l}`)

if (write) {
  const body = `// Generated by \`npm run sim -- --write\` (${samples} duels per cell, skill ${skill}); do not edit by hand.\nexport const MATCHUP_DATA = ${JSON.stringify(table)}\n`
  writeFileSync(OUT, body)
  console.log(`\nWrote ${OUT.pathname}`)
}
